OBJECTION_PLAYBOOK = """
## OBJECTION PLAYBOOK (Hormozi-Style Reframes)

### "It's too expensive / I can't afford it"
WRONG: Discount immediately or justify the price
RIGHT: "I hear you. Can I ask — what's your current monthly marketing budget, and what are you getting for it?"
[Let them answer]
"So right now you're spending $X and getting [nothing/inconsistent results]. We're at $Y with a guarantee. What if I could show you how to pay for this with the first client we bring you?"
Key: Never discount. Reframe to ROI.

### "I need to think about it"
WRONG: "Sure, take your time!"
RIGHT: "Of course — what specifically do you need to think about? Is it the investment, the results, or something else?"
[Isolate the real objection]
"So if we could [address that specific thing], would you be ready to move forward today?"
Key: "Think about it" = hidden objection. Dig until you find it.

### "Send me a proposal and I'll review it"
WRONG: Send it and follow up a week later
RIGHT: "Happy to. Before I put it together, I want to make sure it's exactly what you need. When are you free for a 20-minute call so I can walk you through it? Otherwise it's just a PDF that sits in your inbox."
Key: A proposal you can't present is a dead proposal.

### "I'm already working with someone"
WRONG: Apologize and back off
RIGHT: "That's great — how's it going? What results are you getting right now?"
[Let them answer]
"What would better look like for you? What would need to happen for you to consider making a switch?"
Key: Make them articulate the gap. You didn't lose — they haven't been won yet.

### "I need to talk to my partner/spouse"
WRONG: "Sure, no problem!"
RIGHT: "Of course. Is there any reason we couldn't get them on a quick call together? I want to make sure all your questions get answered at the same time."
If they resist: "What's your gut feeling — is this something you'd want to do if it was just your decision?"
Key: Get the decision-maker on the call.

### "I've been burned before by agencies"
WRONG: Talk about how you're different (everyone says this)
RIGHT: "I completely understand. What happened? What did they promise and what actually happened?"
[Let them vent]
"That's exactly why we built our guarantee. [Explain guarantee]. We're betting on ourselves. The agency that burned you — did they offer you anything like that?"
Key: Their past pain is your present opportunity.

### "We don't have the budget right now"
WRONG: Back off or schedule a call in 3 months
RIGHT: "What would need to change in the business for budget to open up?"
[Listen]
"What if this was the thing that CREATED the budget? What's one client worth to you?"
[ROI calculation]
"So at $X/month, we'd need to close [N] clients to pay for itself. Do you think we could get [N] clients in 90 days?"
Key: Reframe from expense to investment.

### "I want to try it myself first"
WRONG: "Sure, let me know if you need help!"
RIGHT: "How long have you been saying that? What's stopped you so far?"
[Honest answer = time, complexity, not knowing where to start]
"That's exactly what we solve. The average business owner spends 3-4 months and $2,000+ learning what our team already knows. We skip that entirely. What would those 4 months cost you in lost leads?"
Key: Respect the instinct, redirect to the cost of the learning curve.
"""

