HORMOZI_FRAMEWORKS = """
## ALEX HORMOZI CORE FRAMEWORKS

### The Value Equation (from $100M Offers)
Value = (Dream Outcome × Perceived Likelihood of Achievement) / (Time Delay × Effort & Sacrifice)
- Maximize: Dream outcome clarity + believability that YOU can deliver it
- Minimize: How long it takes + how much work they have to do
- A great offer makes the value so obvious that saying no feels stupid

### The Dream Outcome Discovery Process
Never pitch until you know THEIR dream outcome. Ask:
1. "What does success look like for you 12 months from now?"
2. "What's the real cost of where you are right now — in dollars and stress?"
3. "What have you tried before and why didn't it work?"
4. "If we could get you [dream outcome], what would that be worth to you?"
The prospect should sell themselves. Your job is to ask better questions.

### Pain Amplification (Never Skip This)
Pain drives action. Comfort breeds inaction. Before presenting price:
- "How long has this been a problem?"
- "What's it costing you every month you don't fix this?"
- "What happens to the business if nothing changes in 12 months?"
Make the cost of inaction MORE painful than the cost of your service.

### The Value Stack (Never Sell a Single Service)
Stack: Primary service + Bonus 1 + Bonus 2 + Guarantee + Ease of implementation
Example for lead gen agency:
  ✓ Done-for-you Google Ads campaigns ($2,500/mo value)
  ✓ Weekly optimization calls ($1,200/mo value)
  ✓ Lead tracking dashboard ($800/mo value)
  ✓ 30-day results guarantee (priceless)
  ✓ Onboarding in 72 hours (vs. 4-week industry average)
  → Price: $1,500/mo (total value $4,500+)

### Price Anchoring — Always Anchor High First
"Most agencies we compete with charge $5,000–8,000/month for this. We've engineered it to deliver the same results at $2,500 because we've productized the process."
Never give price before you've established value. Price without value = sticker shock.

### The "Save Them From Themselves" Close
When they hesitate: "I get it — the timing never feels perfect. But here's the reality: every month you wait, your competitors are running ads, getting leads, and taking your market share. The real risk isn't investing $X — it's what happens if you don't."

### Grand Slam Offer Structure
1. Name the dream outcome (specific, tangible)
2. Identify the obstacles between them and it
3. Show how you remove each obstacle
4. Price it as a fraction of the value
5. Reverse the risk with a guarantee
"""

